-- StudentHub schema — idempotent, safe to run repeatedly.
-- Source of truth for a fresh database AND for upgrading an existing one.
-- Apply with: npm run db:migrate

-- =====================================================
-- TABLES
-- =====================================================

CREATE TABLE IF NOT EXISTS users (
  id SERIAL PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL,
  password TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  profile_image TEXT,
  bio TEXT
);

CREATE TABLE IF NOT EXISTS posts (
  id SERIAL PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  content TEXT NOT NULL,
  user_id INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  subject VARCHAR(255),
  image_url TEXT
);

CREATE TABLE IF NOT EXISTS comments (
  id SERIAL PRIMARY KEY,
  content TEXT NOT NULL,
  user_id INTEGER NOT NULL,
  post_id INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS likes (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL,
  post_id INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS bookmarks (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL,
  post_id INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Foreign keys (idempotent: pg keeps each constraint's autogenerated
-- name stable, so IF NOT EXISTS only adds what is missing)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_user') THEN
    ALTER TABLE posts
      ADD CONSTRAINT fk_user FOREIGN KEY (user_id)
      REFERENCES users(id) ON DELETE CASCADE;
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'comments_user_id_fkey') THEN
    ALTER TABLE comments
      ADD CONSTRAINT comments_user_id_fkey FOREIGN KEY (user_id)
      REFERENCES users(id) ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'comments_post_id_fkey') THEN
    ALTER TABLE comments
      ADD CONSTRAINT comments_post_id_fkey FOREIGN KEY (post_id)
      REFERENCES posts(id) ON DELETE CASCADE;
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'likes_user_id_fkey') THEN
    ALTER TABLE likes
      ADD CONSTRAINT likes_user_id_fkey FOREIGN KEY (user_id)
      REFERENCES users(id) ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'likes_post_id_fkey') THEN
    ALTER TABLE likes
      ADD CONSTRAINT likes_post_id_fkey FOREIGN KEY (post_id)
      REFERENCES posts(id) ON DELETE CASCADE;
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'bookmarks_user_id_fkey') THEN
    ALTER TABLE bookmarks
      ADD CONSTRAINT bookmarks_user_id_fkey FOREIGN KEY (user_id)
      REFERENCES users(id) ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'bookmarks_post_id_fkey') THEN
    ALTER TABLE bookmarks
      ADD CONSTRAINT bookmarks_post_id_fkey FOREIGN KEY (post_id)
      REFERENCES posts(id) ON DELETE CASCADE;
  END IF;
END $$;

-- Unique guards against duplicate likes/bookmarks
CREATE UNIQUE INDEX IF NOT EXISTS likes_user_id_post_id_key
  ON likes (user_id, post_id);

CREATE UNIQUE INDEX IF NOT EXISTS bookmarks_user_id_post_id_key
  ON bookmarks (user_id, post_id);

-- =====================================================
-- HARDENING
-- =====================================================

-- Normalize timestamps to timestamptz (interprets existing local values
-- in the server timezone; no-op once converted)
ALTER TABLE users     ALTER COLUMN created_at TYPE TIMESTAMPTZ USING created_at AT TIME ZONE current_setting('TimeZone');
ALTER TABLE posts     ALTER COLUMN created_at TYPE TIMESTAMPTZ USING created_at AT TIME ZONE current_setting('TimeZone');
ALTER TABLE comments  ALTER COLUMN created_at TYPE TIMESTAMPTZ USING created_at AT TIME ZONE current_setting('TimeZone');
ALTER TABLE likes     ALTER COLUMN created_at TYPE TIMESTAMPTZ USING created_at AT TIME ZONE current_setting('TimeZone');
ALTER TABLE bookmarks ALTER COLUMN created_at TYPE TIMESTAMPTZ USING created_at AT TIME ZONE current_setting('TimeZone');

ALTER TABLE posts ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ;

-- Case-insensitive email uniqueness (app lowercases before insert)
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_key
  ON users (lower(email));

-- Feed / profile / engagement lookups
CREATE INDEX IF NOT EXISTS idx_posts_created  ON posts (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_posts_user     ON posts (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_posts_subject  ON posts (subject, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_comments_post  ON comments (post_id, created_at);
CREATE INDEX IF NOT EXISTS idx_likes_post     ON likes (post_id);
CREATE INDEX IF NOT EXISTS idx_bookmarks_user ON bookmarks (user_id, created_at DESC);
